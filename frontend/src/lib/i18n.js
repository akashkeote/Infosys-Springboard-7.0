const LangContext = createContext({ lang: "en", setLang: () => {}, t: T.en });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState("en");

  useEffect(() => {
    const stored = localStorage.getItem("govgrant-lang");
    if (stored && T[stored]) setLangState(stored);
  }, []);

  const setLang = (code) => {
    setLangState(code);
    localStorage.setItem("govgrant-lang", code);
    document.documentElement.lang = code;
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t: T[lang] || T.en }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
